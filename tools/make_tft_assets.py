#!/usr/bin/env python3
"""Generates firmware/MeowIsland/cat_assets.h: the phone widgets' cat artwork as small RGB565 bitmaps for the ESP32 TFT.
Source art: plugins/widgets/res/drawable-nodpi (the same PNGs the Android widgets use). Needs Pillow:  pip install pillow
Run from the repository root:  python tools/make_tft_assets.py
"""
from PIL import Image
import os, sys

SRC = os.path.join("plugins", "widgets", "res", "drawable-nodpi")
OUT = os.path.join("firmware", "MeowIsland", "cat_assets.h")
TILE = (36, 36, 44)      # C_TILE: behind the dancing cat (music screen)
BG = (3, 1, 6)           # C_BG: behind the step-card cat

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

def convert(name, size, bg):
    im = Image.open(os.path.join(SRC, name + ".png")).convert("RGBA")
    im = im.resize(size, Image.LANCZOS)
    base = Image.new("RGBA", size, bg + (255,))
    base.alpha_composite(im)
    px = base.convert("RGB").load()
    return [rgb565(*px[x, y]) for y in range(size[1]) for x in range(size[0])]

def emit(f, ident, data, per_line=16):
    f.write("static const uint16_t %s[%d] PROGMEM = {\n" % (ident, len(data)))
    for i in range(0, len(data), per_line):
        f.write("  " + ",".join("0x%04X" % v for v in data[i:i + per_line]) + ",\n")
    f.write("};\n")

def main():
    DANCE = (88, 88); CAT = (96, 65)
    with open(OUT, "w") as f:
        f.write("// GENERATED by tools/make_tft_assets.py from the app's own cat artwork. Do not edit by hand.\n#pragma once\n#include <Arduino.h>\n\n")
        f.write("constexpr int CAT_DANCE_W = %d, CAT_DANCE_H = %d, CAT_DANCE_FRAMES = 6;\n" % (DANCE[0], DANCE[1]))
        f.write("constexpr int CAT_STEP_W = %d, CAT_STEP_H = %d;\n\n" % CAT)
        for i in range(6):
            emit(f, "CAT_DANCE_%d" % i, convert("meow_dance_%d" % i, DANCE, TILE))
        emit(f, "CAT_DANCE_IDLE", convert("meow_dance_idle", DANCE, TILE))
        emit(f, "CAT_STEP_HAPPY", convert("meow_cat_happy", CAT, BG))
        emit(f, "CAT_STEP_ANGRY", convert("meow_cat_angry", CAT, BG))
        f.write("\nstatic const uint16_t* const CAT_DANCE[CAT_DANCE_FRAMES] = {CAT_DANCE_0, CAT_DANCE_1, CAT_DANCE_2, CAT_DANCE_3, CAT_DANCE_4, CAT_DANCE_5};\n")
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB source,", (6 * DANCE[0] * DANCE[1] + DANCE[0] * DANCE[1] + 2 * CAT[0] * CAT[1]) * 2 // 1024, "KB of flash")

if __name__ == "__main__":
    sys.exit(main())
